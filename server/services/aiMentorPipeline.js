import { contextCollector } from "./contextCollector.js";
import { firebaseHintService } from "./firebaseHintService.js";
import { llmService } from "./llmService.js";
import { hintValidator } from "./hintValidator.js";
import { hintHistoryService } from "./hintHistoryService.js";
import { hintLevelManager } from "./hintLevelManager.js";
class AiMentorPipeline {
  async execute(request) {
    const startTime = Date.now();
    const context = contextCollector.collect(request);
    const normalizedLevel = hintLevelManager.normalizeLevel(context.hintLevel);
    context.hintLevel = normalizedLevel;
    const firebaseMatch = await firebaseHintService.findMatchingHint(
      context.programId,
      context.section,
      context.studentInput,
      context.hintLevel
    );
    if (firebaseMatch.matched && firebaseMatch.hint) {
      context.curriculumHint = firebaseMatch.hint.hint;
      context.curriculumInput = firebaseMatch.hint.inputPattern;
    } else {
      const curriculumMatch = await firebaseHintService.findBestMatchingPair(
        context.programId,
        context.section,
        context.studentInput || context.studentWorksheet || ""
      );
      if (curriculumMatch && curriculumMatch.bestPair) {
        context.curriculumHint = curriculumMatch.bestPair.hint;
        context.curriculumInput = curriculumMatch.bestPair.input;
      }
    }
    let validatedOutput;
    try {
      const rawLlmOutput = await llmService.generateHint(context);
      const validation = hintValidator.validate(rawLlmOutput, context);
      validatedOutput = validation.sanitizedOutput;
      if (validatedOutput && validatedOutput.hint) {
        const h = validatedOutput.hint.trim();
        if (!/^(🌟|coach maara|hey there|awesome|great work|spot on)/i.test(h)) {
          validatedOutput.hint = `\u{1F31F} Coach Maara here! ${h.charAt(0).toUpperCase() + h.slice(1)}`;
        }
      }
      const prevs = context.previousHints || [];
      const isRepeated = prevs.some(
        (p) => p.trim().toLowerCase() === validatedOutput.hint.trim().toLowerCase() || p.length > 25 && validatedOutput.hint.length > 25 && p.slice(0, 35).toLowerCase() === validatedOutput.hint.slice(0, 35).toLowerCase()
      );
      if (isRepeated) {
        console.info("[AiMentorPipeline] Generated hint was repeated, selecting fresh pedagogical variation...");
        const fresh = llmService.generateFallbackHint(context);
        validatedOutput = fresh;
      }
    } catch (err) {
      console.warn("[AiMentorPipeline] LLM call failed, falling back to pedagogical fallback engine:", err);
      validatedOutput = llmService.generateFallbackHint(context);
    }
    await firebaseHintService.saveGeneratedHint(
      context.programId,
      context.section,
      context.studentInput || `${context.section} help`,
      validatedOutput.hint,
      validatedOutput.hintLevel,
      validatedOutput.concept,
      "llm"
    );
    hintHistoryService.logHintDelivered(
      context.userId,
      context.programId,
      context.section,
      context.studentInput,
      context.studentCode,
      validatedOutput.hint,
      validatedOutput.hintLevel,
      validatedOutput.concept,
      "llm",
      "attempting"
    );
    return {
      success: true,
      hint: validatedOutput.hint,
      hintLevel: validatedOutput.hintLevel,
      source: "llm",
      concept: validatedOutput.concept,
      section: context.section,
      shouldRevealSolution: validatedOutput.shouldRevealSolution,
      nextSuggestedAction: validatedOutput.nextSuggestedAction,
      cachedInFirebase: true,
      personalizedReason: `Generated by Gemini AI Mentor tailored to Stage: ${context.section.toUpperCase()} at Hint Level ${context.hintLevel}.`
    };
  }
}
const aiMentorPipeline = new AiMentorPipeline();
export {
  AiMentorPipeline,
  aiMentorPipeline
};
